// ─── Auth Tests ───────────────────────────────────────────────────────────────

func TestAuthRequired(t *testing.T) {
	handler := newTestRouter()

	// Protected endpoints should require auth
	protectedPaths := []string{
		"/api/v1/organizations",
		"/api/v1/users",
		"/api/v1/projects",
		"/api/v1/credentials",
		"/api/v1/inventories",
		"/api/v1/execution-environments",
		"/api/v1/job-templates",
		"/api/v1/jobs",
	}

	for _, path := range protectedPaths {
		w := makeRequest(t, handler, "GET", path)
		if w.Code != http.StatusUnauthorized {
			t.Errorf("%s: status = %d, want %d", path, w.Code, http.StatusUnauthorized)
		}
	}
}

func TestInvalidAuth(t *testing.T) {
	handler := newTestRouter()

	req := httptest.NewRequest("GET", "/api/v1/organizations", http.NoBody)
	req.Header.Set("Authorization", "Bearer invalid-token")
	w := httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Code != http.StatusUnauthorized {
		t.Errorf("status = %d, want %d", w.Code, http.StatusUnauthorized)
	}
}

// ─── Request ID Tests ─────────────────────────────────────────────────────────

func TestRequestID(t *testing.T) {
	handler := newTestRouter()

	req := httptest.NewRequest("GET", "/healthz", http.NoBody)
	req.Header.Set("X-Request-ID", "test-request-id")
	w := httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Header().Get("X-Request-ID") != "test-request-id" {
		t.Errorf("X-Request-ID = %q, want %q", w.Header().Get("X-Request-ID"), "test-request-id")
	}
}

func TestRequestID_AutoGenerated(t *testing.T) {
	handler := newTestRouter()
	w := makeRequest(t, handler, "GET", "/healthz")

	if w.Header().Get("X-Request-ID") == "" {
		t.Error("X-Request-ID should be auto-generated")
	}
}

